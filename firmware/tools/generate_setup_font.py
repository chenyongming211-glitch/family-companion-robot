#!/usr/bin/env python3
"""Regenerate the public offline setup glyph subset on the cloud build host."""
from pathlib import Path
import argparse
from PIL import Image,ImageFont,ImageDraw
import re
parser=argparse.ArgumentParser(description=__doc__)
parser.add_argument('--font',type=Path,required=True)
parser.add_argument('--output-dir',type=Path,required=True)
args=parser.parse_args()
p=args.output_dir
p.mkdir(parents=True,exist_ok=True)
src=(Path(__file__).resolve().parents[1]/'overlays/onboarding/family_onboarding.cc').read_text()
strings=re.findall(r'(?:title|detail)="([^"]*)"',src)
chars=sorted(set(''.join(strings)))
fontpath=str(args.font)
f=ImageFont.truetype(fontpath,30,index=2)
if f.getname()[0]!='Noto Sans CJK SC':raise ValueError('requires NotoSansCJK SC face at index2')
out=['/* Generated from Debian fonts-noto-cjk NotoSansCJK-Regular.ttc (SC face), 30px.',' * Font licensed SIL Open Font License 1.1; see accompanying font-license.txt.',' * Generated by generate_setup_font.py using Pillow/FreeType; static A8 subset.',' * No runtime font dependencies; contains every title/detail literal in family_onboarding.cc. */','#include "family_setup_font.h"','#include <stddef.h>']
entries=[]
for c in chars:
 x0,y0,x1,y1=f.getbbox(c,anchor='ls');w=x1-x0;h=y1-y0
 im=Image.new('L',(max(1,w),max(1,h)));ImageDraw.Draw(im).text((-x0,-y0),c,font=f,fill=255,anchor='ls')
 name='g_'+str(ord(c));out.append('static const uint8_t '+name+'[] = {'+','.join(map(str,im.tobytes()))+'};')
 entries.append((ord(c),round(f.getlength(c)),w,h,x0,-y1,name))
out+=['typedef struct {uint32_t code; uint16_t adv,w,h; int16_t x,y; const uint8_t *data;} Glyph;','static const Glyph glyphs[] = {']
for e in entries:out.append('{'+','.join(map(str,e))+'},')
out+=['};','static bool glyph_dsc(const lv_font_t *font, lv_font_glyph_dsc_t *d, uint32_t code, uint32_t next) {','    (void)font; (void)next;','    for(size_t i=0;i<sizeof(glyphs)/sizeof(glyphs[0]);i++) {','        const Glyph *g=&glyphs[i]; if(g->code != code) continue;','        d->adv_w=g->adv; d->box_w=g->w; d->box_h=g->h; d->ofs_x=g->x; d->ofs_y=g->y;','        d->stride=g->w; d->format=LV_FONT_GLYPH_FORMAT_A8; d->gid.index=(uint32_t)i; return true;','    }','    return false;','}','static const void *glyph_bitmap(lv_font_glyph_dsc_t *d, lv_draw_buf_t *buf) {','    (void)buf; return glyphs[d->gid.index].data;','}','const lv_font_t family_setup_font = {','.get_glyph_dsc=glyph_dsc, .get_glyph_bitmap=glyph_bitmap,','.line_height=44, .base_line=9, .static_bitmap=1,','};']
(p/'family_setup_font.c').write_text('\n'.join(out)+'\n')
(p/'family_setup_font.h').write_text('#pragma once\n#include <lvgl.h>\n#ifdef __cplusplus\nextern "C" {\n#endif\nextern const lv_font_t family_setup_font;\n#ifdef __cplusplus\n}\n#endif\n')
print('font characters',len(chars),'glyph bytes',sum(max(1,e[2])*max(1,e[3]) for e in entries),'labels',strings)
