#!/usr/bin/env python3
"""Regenerate public offline setup/date glyph subsets on the cloud build host."""
from pathlib import Path
import argparse
from PIL import Image,ImageFont,ImageDraw
import re
parser=argparse.ArgumentParser(description=__doc__)
parser.add_argument('--font',type=Path,required=True)
parser.add_argument('--output-dir',type=Path,required=True)
parser.add_argument('--text',help='explicit glyph set; default reads setup status literals')
parser.add_argument('--name',default='family_setup_font',help='output filename stem')
parser.add_argument('--symbol',help='C font symbol; defaults to filename stem')
parser.add_argument('--size',type=int,default=30,help='glyph size in pixels')
parser.add_argument('--line-height',type=int,default=44,help='font line height in pixels')
args=parser.parse_args()
symbol=args.symbol or args.name
if not all(re.fullmatch(r'[a-z][a-z0-9_]*',value) for value in (args.name,symbol)):
    parser.error('font name and symbol must be lowercase C identifiers')
if not 1 <= args.size <= 96 or not args.size <= args.line_height <= 128:
    parser.error('requires size 1..96 and line height size..128')
p=args.output_dir
p.mkdir(parents=True,exist_ok=True)
if args.text is None:
    src=(Path(__file__).resolve().parents[1]/'overlays/onboarding/family_onboarding.cc').read_text()
    strings=re.findall(r'(?:title|detail)="([^"]*)"',src)
else:
    strings=[args.text]
chars=sorted(set(''.join(strings)))
fontpath=str(args.font)
f=ImageFont.truetype(fontpath,args.size,index=2)
if f.getname()[0]!='Noto Sans CJK SC':raise ValueError('requires NotoSansCJK SC face at index2')
coverage=('contains every title/detail literal in family_onboarding.cc.' if args.text is None
          else 'contains the explicit --text glyph set.')
license_note=('see accompanying font-license.txt.' if args.text is None
              else 'see firmware/overlays/onboarding/font-license.txt.')
out=[f'/* Generated from Debian fonts-noto-cjk NotoSansCJK-Regular.ttc (SC face), {args.size}px.',
     ' * Font licensed SIL Open Font License 1.1; '+license_note,
     ' * Generated by generate_setup_font.py using Pillow/FreeType; static A8 subset.',
     ' * No runtime font dependencies; '+coverage+' */',
     '#include "'+args.name+'.h"','#include <stddef.h>']
entries=[]
for c in chars:
 x0,y0,x1,y1=f.getbbox(c,anchor='ls');w=x1-x0;h=y1-y0
 im=Image.new('L',(max(1,w),max(1,h)));ImageDraw.Draw(im).text((-x0,-y0),c,font=f,fill=255,anchor='ls')
 name='g_'+str(ord(c));out.append('static const uint8_t '+name+'[] = {'+','.join(map(str,im.tobytes()))+'};')
 entries.append((ord(c),round(f.getlength(c)),w,h,x0,-y1,name))
out+=['typedef struct {uint32_t code; uint16_t adv,w,h; int16_t x,y; const uint8_t *data;} Glyph;','static const Glyph glyphs[] = {']
for e in entries:out.append('{'+','.join(map(str,e))+'},')
out+=['};','static bool glyph_dsc(const lv_font_t *font, lv_font_glyph_dsc_t *d, uint32_t code, uint32_t next) {','    (void)font; (void)next;','    for(size_t i=0;i<sizeof(glyphs)/sizeof(glyphs[0]);i++) {','        const Glyph *g=&glyphs[i]; if(g->code != code) continue;','        d->adv_w=g->adv; d->box_w=g->w; d->box_h=g->h; d->ofs_x=g->x; d->ofs_y=g->y;','        d->stride=g->w; d->format=LV_FONT_GLYPH_FORMAT_A8; d->gid.index=(uint32_t)i; return true;','    }','    return false;','}','static const void *glyph_bitmap(lv_font_glyph_dsc_t *d, lv_draw_buf_t *buf) {','    (void)buf; return glyphs[d->gid.index].data;','}','const lv_font_t '+symbol+' = {','.get_glyph_dsc=glyph_dsc, .get_glyph_bitmap=glyph_bitmap,',f'.line_height={args.line_height}, .base_line=9, .static_bitmap=1,','};']
(p/(args.name+'.c')).write_text('\n'.join(out)+'\n')
(p/(args.name+'.h')).write_text('#pragma once\n#include <lvgl.h>\n#ifdef __cplusplus\nextern "C" {\n#endif\nextern const lv_font_t '+symbol+';\n#ifdef __cplusplus\n}\n#endif\n')
print('font characters',len(chars),'glyph bytes',sum(max(1,e[2])*max(1,e[3]) for e in entries),'labels',strings)
